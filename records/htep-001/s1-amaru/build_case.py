#!/usr/bin/env python3
"""Rebuild actions.csv and sources.csv from the exact Koios snapshot supplied with --snapshot.
Relationship assertions are manually reviewed and are NOT generated by this script.
"""
import argparse,csv,hashlib,json,pathlib
EXPECTED_SHA256="8836d85e6530613d9042cc1f1d7e11e9e6e5a8e9391cda32be527f5a63e7fcd8"
ACTIONS=[
 ('A0','gov_action1h4ygjv0hjfj3lmafcm76rpdzcm8vsvj9k5wejn3npyxwxm3fesnqqw9kxxz'),
 ('A1','gov_action1vrkk4dpuss8l3z9g4uc2rmf8ks0f7j534zvz9v4k85dlc54wa3zsqq68rx0'),
 ('A2','gov_action19uhuy5uame2s60yrh6n8cyds8ps5q7tkh05dqlzmpcfy429p9w4qq5ll3g0'),
]
def write_csv(p,h,rs):
 with p.open('w',encoding='utf-8',newline='') as f:
  w=csv.writer(f);w.writerow(h);w.writerows(rs)
def main():
 p=argparse.ArgumentParser();p.add_argument('--snapshot',type=pathlib.Path,required=True);p.add_argument('--out',type=pathlib.Path,default=pathlib.Path('.'));a=p.parse_args()
 digest=hashlib.sha256(a.snapshot.read_bytes()).hexdigest()
 if digest!=EXPECTED_SHA256: raise ValueError('Snapshot checksum mismatch; do not silently refresh this record')
 data=json.loads(a.snapshot.read_text());rows=data['rows'];events=[];sources=[]
 for key,aid in ACTIONS:
  matches=[r for r in rows if r['proposal_id']==aid]
  if len(matches)!=1:raise ValueError(f'Expected exactly one source row for {aid}')
  r=matches[0];withdrawals=r.get('withdrawal') or [];lov=sum(int(w['amount']) for w in withdrawals)
  events.append([key,aid,r['proposal_type'],r['proposed_epoch'],r.get('ratified_epoch') or '',r.get('enacted_epoch') or '',r.get('expired_epoch') or '',str(lov),str(len(withdrawals)),r['meta_json']['body'].get('title',''),r['meta_url'],'Koios proposal_list captured snapshot; withdrawal is indexed on-chain TWD amount, not downstream expenditure'])
  sources.append([key,aid,f'rows[proposal_id={aid}]',r['meta_url'],r.get('meta_hash') or '',data['retrieved_at_utc'],'koios_indexed_governance_action','Koios snapshot contains indexed action and proposer-authored meta_json; metadata not separately fetched or verified against IPFS'])
 a.out.mkdir(exist_ok=True,parents=True)
 write_csv(a.out/'actions.csv',['case_local_key','governance_action_id','action_type','submitted_epoch','ratified_epoch','enacted_epoch','expired_epoch','withdrawal_lovelace','withdrawal_recipient_count','source_metadata_title','metadata_url','scope_note'],events)
 write_csv(a.out/'sources.csv',['case_local_key','governance_action_id','snapshot_locator','original_metadata_url','metadata_hash_reported_by_koios','snapshot_retrieved_at_utc','source_type','verification_boundary'],sources)
if __name__=='__main__':main()
